import { chromium } from './pw.mjs';
const url = process.env.QA_URL || 'http://localhost:8899/';
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const errs = [];
for (const [name, opts] of [['d', { viewport: { width: 1440, height: 900 } }], ['m', { viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 }]]) {
  const page = await browser.newPage(opts);
  await page.addInitScript(() => { const t = setInterval(() => { const x = document.querySelector('.promo.open .promo-x'); if (x) { x.click(); clearInterval(t); } }, 50); });
  page.on('pageerror', e => errs.push(`[${name}] ${e.message}`));
  page.on('console', m => m.type() === 'error' && errs.push(`[${name}] ${m.text()}`));
  await page.goto(url); await page.waitForTimeout(1500);
  await page.locator('#cartBtn').click(); await page.waitForTimeout(600);
  await page.screenshot({ path: `qa/co-${name}-empty.png` });
  await page.locator('#cpClose').click(); await page.waitForTimeout(400);
  await page.locator('#heroAdd').click(); await page.waitForTimeout(300);
  await page.locator('#heroAdd').click(); await page.waitForTimeout(300);
  await page.locator('#index button').nth(3).click(); await page.waitForTimeout(700);
  for (let i = 0; i < 2; i++) await page.locator('#qPlus').click();
  await page.locator('#dAdd').click(); await page.waitForTimeout(300);
  console.log(name, 'note:', await page.locator('#dNote').textContent());
  await page.locator('#dGo').click(); await page.waitForTimeout(700);
  console.log(name, 'cart lines:', await page.locator('.line').count(), '| total:', await page.locator('.cp-foot .total').textContent(), '| stamps:', await page.locator('.stampbar span').first().textContent());
  await page.screenshot({ path: `qa/co-${name}-cart.png` });
  await page.locator('[data-act=next]').click(); await page.waitForTimeout(400);
  await page.locator('[data-act=submit]').click(); await page.waitForTimeout(300);
  console.log(name, 'validation errors:', await page.locator('.field.bad').count());
  await page.screenshot({ path: `qa/co-${name}-errors.png` });
  await page.locator('#f-name').fill('Lin');
  await page.locator('#f-phone').fill('+34 612 345 678');
  await page.locator('[data-mode=postal]').click(); await page.waitForTimeout(300);
  console.log(name, 'postal total:', await page.locator('.cp-foot .total').textContent());
  await page.screenshot({ path: `qa/co-${name}-details.png` });
  for (const [k, v] of [['recipient', 'Lin Chen'], ['street', 'Calle Mayor 1'], ['cp', '28013'], ['city', 'Madrid'], ['province', 'Madrid']]) await page.locator(`#f-${k}`).fill(v);
  await page.locator('[data-act=submit]').click(); await page.waitForSelector('.done-h', { timeout: 8000 });
  console.log(name, 'done:', await page.locator('.done-h h3').textContent(), '| order:', await page.locator('.done-h b.num').textContent(), '| cart now:', await page.locator('#cartCnt').textContent(), '| wa:', (await page.locator('.cp-foot a[href*="wa.me"]').getAttribute('href')).slice(0, 60));
  await page.screenshot({ path: `qa/co-${name}-done.png` });
  await page.close();
}
console.log('errors:', errs.length ? errs : 'none');
await browser.close();
